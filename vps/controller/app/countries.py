def country_names(value: str) -> list[str]:
    """Noms Gluetun pour un code à deux lettres, ou la valeur telle quelle (nom complet)."""
    return list(COUNTRIES.get(value.casefold(), (value,)))


def same_country(a: str | None, b: str | None) -> bool:
    return (a or "").casefold() == (b or "").casefold()


def in_country(current: str | None, names: list[str]) -> bool:
    return any(same_country(current, name) for name in names)
